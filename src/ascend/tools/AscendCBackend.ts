// ── backend ──────────────────────────────────────────────────────────────────

export class AscendCBackend implements KernelBackend {
  readonly id = 'ascend-c' as const

  emit(spec: OperatorSpec, tiling?: TilingHint): KernelArtifact {
    const op = sanitizeOp(spec.op_name)
    const cls = classStem(op)
    const files: ProjectFile[] = [
      { path: `csrc/${op}_custom.asc`, content: kernelAsc(op, cls, tiling) },
      { path: 'csrc/pybind11.asc', content: pybindAsc(op) },
      { path: 'setup.py', content: setupPy() },
      { path: `test_${op}.py`, content: testPy(op) },
    ]
    return {
      files,
      entry_kernel: `${op}_custom`,
      op_name: op,
      module_name: 'custom_ops_lib',
    }
  }
}
