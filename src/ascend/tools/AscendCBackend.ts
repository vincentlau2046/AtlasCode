/** Sanitize an op name to a valid C/Python identifier stem. */
function sanitizeOp(name: string): string {
  return (name || 'unnamed_op').replace(/[^a-zA-Z0-9_]/g, '_')
}

/** PascalCase for the kernel class: gelu → Gelu, gelu_custom → GeluCustom. */
function classStem(op: string): string {
  return op.split('_').filter(Boolean).map(s => s[0].toUpperCase() + s.slice(1)).join('')
}

