/**
 * AscendCBackend — MVP KernelBackend for Ascend C (bisheng-compiled).
 *
 * Emits the four-piece operator project scaffold derived verbatim (structure)
 * from op-examples/ (GELU) and its template source op-plugin/examples/cpp_extension.
 *
 * The four files:
 *   1. csrc/<op>_custom.asc   — kernel class + __global__ __vector__ entry + host launcher
 *   2. csrc/pybind11.asc       — PYBIND11_MODULE binding (compiled by the same bisheng call)
 *   3. setup.py                — bisheng build driver (npu-smi arch probe + ABI + dep paths)
 *   4. test_<op>.py            — golden test (numpy ref vs NPU, np.allclose)
 *
 * What is scaffolded vs placeholder:
 *   - SCAFFOLDED (faithful): includes, kernel entry signature (__global__ __vector__),
 *     Kernel<Op> class skeleton (Init/Process/CopyIn/Compute/CopyOut three-stage pipeline,
 *     BUFFER_NUM=2 double-buffer), host launcher (方式3: stream(false)+OpCommand),
 *     setup.py bisheng compile_cmd, golden-test harness structure.
 *   - PLACEHOLDER (agent fills via Read/Edit/Write): the Compute() math body
 *     (op-specific: GELU = Mul→Erf→Mul→Add→Mul; other ops differ), the numpy
 *     reference formula in test_<op>.py.
 *
 * Official grounding: memory `ascend-bisheng-compile-form`.
 *
 * M3-S3：从 AtlasHarness src/tools/ascend/AscendCBackend.ts 逐字移植（仅改导入路径
 * `./KernelBackend.js` → `./KernelBackend`，对齐 AtlasCode no-ext 导入约定）。
 */

